/**
 * P0 renderer build.
 *
 * Reuses the plugin's `src/` modules with the same tiny CommonJS loader as
 * `../build.mjs`, but renders the shell directly instead of registering a
 * Harness slot. React 18 UMD builds are copied in as the runtime; no bundler
 * subprocess is needed.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(fileURLToPath(import.meta.url))
const srcRoot = path.resolve(root, '..', 'src')
const outDir = path.join(root, 'renderer')
const vendorDir = path.join(outDir, 'vendor')

function listModules(dir) {
  const out = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...listModules(full))
    else if (entry.isFile() && entry.name.endsWith('.js')) out.push(full)
  }
  return out
}

const modules = listModules(srcRoot).sort().map((file) => {
  const id = path.relative(srcRoot, file).split(path.sep).join('/')
  return { id, source: fs.readFileSync(file, 'utf8') }
})

const moduleObject = modules.map(({ id, source }) => {
  const indented = source
    .split('\n')
    .map((line) => (line.length === 0 ? '' : `      ${line}`))
    .join('\n')
  return `    ${JSON.stringify(id)}: function (module, exports, require) {\n${indented}\n    },`
}).join('\n')

const mammothPath = path.resolve(root, '..', 'vendor', 'mammoth.browser.min.js')
const mammothBundle = fs.existsSync(mammothPath) ? fs.readFileSync(mammothPath, 'utf8') : ''

fs.mkdirSync(vendorDir, { recursive: true })
fs.copyFileSync(
  path.join(root, 'node_modules', 'react', 'umd', 'react.production.min.js'),
  path.join(vendorDir, 'react.js'),
)
fs.copyFileSync(
  path.join(root, 'node_modules', 'react-dom', 'umd', 'react-dom.production.min.js'),
  path.join(vendorDir, 'react-dom.js'),
)

const output = `${mammothBundle === '' ? '' : `/* mammoth 1.13.0 browser bundle; BSD-2-Clause, see vendor/LICENSE.mammoth */\n${mammothBundle}\n\n`}/* Generated by desktop/build.mjs. */
(function () {
  const React = window.React
  const ReactDOM = window.ReactDOM
  const modules = {
${moduleObject}
  }
  const cache = Object.create(null)

  function normalize(request, from) {
    const base = from.split('/').slice(0, -1)
    const parts = (base.join('/') + '/' + request).split('/')
    const out = []
    for (const part of parts) {
      if (part === '' || part === '.') continue
      if (part === '..') out.pop()
      else out.push(part)
    }
    let id = out.join('/')
    if (!id.endsWith('.js')) id += '.js'
    return id
  }

  function load(id) {
    if (cache[id] !== undefined) return cache[id].exports
    const factory = modules[id]
    if (factory === undefined) throw new Error('Unknown module: ' + id)
    const module = { exports: {} }
    cache[id] = module
    factory(module, module.exports, (request) => {
      if (request === 'react') return React
      if (!request.startsWith('.')) throw new Error('Unknown external module: ' + request)
      return load(normalize(request, id))
    })
    return module.exports
  }

  const { ZH, EN } = load('locales.js')
  const { LearningShell } = load('shell.js')
  const { WelcomeScreen } = load('settings/WelcomeScreen.js')

  const tables = new Map()
  const locale = {
    register(_namespace, language, table) {
      tables.set(language, table)
    },
    bind() {
      return (key) => {
        const table = tables.get('zh')
        return table !== undefined && table[key] !== undefined ? table[key] : key
      }
    },
    subscribe() {
      return () => {}
    },
  }
  locale.register('typing-practice', 'zh', ZH)
  locale.register('typing-practice', 'en', EN)

  const ctx = { locale }
  let root = null

  function mount(element) {
    if (root === null) root = ReactDOM.createRoot(document.getElementById('root'))
    root.render(element)
  }

  function renderShell() {
    mount(React.createElement(LearningShell, { ctx }))
  }

  function renderWelcome() {
    mount(React.createElement(WelcomeScreen, {
      onDone: () => {
        try {
          window.localStorage.setItem('typing-practice:onboarded', '1')
        } catch {
          // A blocked localStorage only means the wizard shows again next time.
        }
        renderShell()
      },
    }))
  }

  async function boot() {
    // P2: move a key left in localStorage by the P0 build into the OS key
    // store before the UI queries /status for the first time.
    if (window.tpDesktop) {
      try {
        const status = await window.tpDesktop.hasApiKey()
        if (status?.configured !== true) {
          const legacy = window.localStorage.getItem('typing-practice:deepseek-api-key')
          if (typeof legacy === 'string' && legacy.trim().length > 0) {
            const saved = await window.tpDesktop.setApiKey(legacy.trim())
            if (saved?.ok === true) {
              window.localStorage.removeItem('typing-practice:deepseek-api-key')
            }
          }
        }
      } catch {
        // The settings panel can still migrate later.
      }
    }

    let onboarded = false
    try {
      onboarded = window.localStorage.getItem('typing-practice:onboarded') === '1'
    } catch {
      onboarded = false
    }

    if (window.tpDesktop && !onboarded) {
      let configured = false
      try {
        const status = await window.tpDesktop.hasApiKey()
        configured = status?.configured === true
      } catch {
        configured = false
      }
      if (!configured) {
        renderWelcome()
        return
      }
      try {
        window.localStorage.setItem('typing-practice:onboarded', '1')
      } catch {
        // Ignore storage failures.
      }
    }

    renderShell()
  }

  void boot()
})()
`

fs.writeFileSync(path.join(outDir, 'app.bundle.js'), output, 'utf8')
console.log(`built desktop renderer from ${modules.length} modules`)
